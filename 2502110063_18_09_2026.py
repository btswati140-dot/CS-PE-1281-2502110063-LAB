def parse_line(line):
    """Parse a product line."""

    parts = line.strip().split(",")

    if len(parts) != 3:
        raise ValueError("Expected 3 fields")

    name = parts[0].strip()
    price = float(parts[1])
    quantity = int(parts[2])

    if not name:
        raise ValueError("Product name is empty")

    if price < 0:
        raise ValueError("Price cannot be negative")

    if quantity < 0:
        raise ValueError("Quantity cannot be negative")

    return {
        "name": name,
        "price": price,
        "quantity": quantity
    }


def process_products(lines):
    report = []
    rejects = []

    for line in lines:
        try:
            product = parse_line(line)
            report.append(product)

        except ValueError as error:
            rejects.append({
                "line": line,
                "reason": str(error)
            })

        except (TypeError, AttributeError) as error:
            rejects.append({
                "line": line,
                "reason": str(error)
            })

    # Guarded average
    if report:
        average_price = sum(
            item["price"] for item in report
        ) / len(report)
    else:
        average_price = 0

    print("\nREPORT")
    print("-" * 40)

    for item in report:
        print(item)

    print(f"\nAverage price: {average_price:.2f}")

    print("\nREJECTS TABLE")
    print("-" * 60)

    if rejects:
        for item in rejects:
            print(f"Line: {item['line']}")
            print(f"Reason: {item['reason']}")
            print("-" * 40)
    else:
        print("No rejected lines.")

    return report, rejects


