# Work Order 07: Machine operating class

class SpecViolation(Exception):
    """Raised when a machine job violates operating specifications."""
    pass


class Machine:

    def __init__(self, machine_id, max_quantity):
        self.machine_id = machine_id
        self.max_quantity = max_quantity
        self.jobs_completed = 0

    def operate(self, part_code, quantity):

        print(f"\nMachine {self.machine_id}: Processing {part_code}")

        # Validate operating specifications
        if not part_code:
            raise SpecViolation("Missing part code")

        if quantity <= 0:
            raise SpecViolation("Quantity must be greater than zero")

        if quantity > self.max_quantity:
            raise SpecViolation(
                f"Quantity {quantity} exceeds machine capacity "
                f"of {self.max_quantity}"
            )

        # Successful operation
        self.jobs_completed += 1

        print("Job completed successfully.")
        return True


# DRIVING PROGRAM

def main():

    # Create machines
    machines = [
        Machine("M001", 100),
        Machine("M002", 50),
        Machine("M003", 200)
    ]

    # Test jobs assigned to machines
    jobs = [
        ("M001", "ABC-123", 80),
        ("M002", "DEF-456", 75),   # Exceeds capacity
        ("M003", "XYZ-789", 150),
        ("M001", "BAD-123", -5),   # Invalid quantity
        ("M002", "GHI-123", 30)
    ]

    machine_lookup = {
        machine.machine_id: machine
        for machine in machines
    }

    completed = 0
    failed = 0

    print("FLEET OPERATIONS STARTED")
    print("=" * 50)

    for machine_id, part_code, quantity in jobs:

        machine = machine_lookup[machine_id]

        try:
            machine.operate(part_code, quantity)
            completed += 1

        except SpecViolation as error:
            failed += 1

            print(
                f"JOB REJECTED on {machine_id}: {error}"
            )

            print("Continuing with next job...")

    # FINAL FLEET REPORT
    print("\nFLEET OPERATIONS SUMMARY")
    print("=" * 50)

    for machine in machines:
        print(
            f"{machine.machine_id}: "
            f"{machine.jobs_completed} jobs completed"
        )

    print("-" * 50)
    print("Total completed:", completed)
    print("Total failed:", failed)
    print("Fleet processing finished.")


if __name__ == "__main__":
    main()

