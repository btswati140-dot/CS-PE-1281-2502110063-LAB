import os
import csv
from collections import defaultdict
from datetime import datetime

INPUT_FILE = "data/shift_log.txt"
REPORT_FILE = "data/report.txt"
REJECTS_FILE = "data/rejects.csv"


def parse_record(line):
    """Parse one CSV record."""
    return next(csv.reader([line]))


def validate_record(fields):
    """Validate a shift log record."""

    if len(fields) != 5:
        return "Incorrect number of fields"

    work_order, date, employee, shift, hours = fields

    if not work_order.strip():
        return "Missing work order"

    try:
        datetime.strptime(date.strip(), "%Y-%m-%d")
    except ValueError:
        return "Invalid date"

    if not employee.strip():
        return "Missing employee name"

    if not all(c.isalpha() or c.isspace()
               for c in employee.strip()):
        return "Invalid employee name"

    if shift.strip().lower() not in ("day", "night"):
        return "Invalid shift"

    try:
        hours = float(hours)
    except ValueError:
        return "Hours must be numeric"

    if hours <= 0 or hours > 24:
        return "Hours must be between 0 and 24"

    return None


def main():

    os.makedirs("data", exist_ok=True)

    aggregates = defaultdict(float)
    rejects = []

    # READ
    try:
        with open(INPUT_FILE, "r", newline="") as file:
            lines = file.readlines()
    except FileNotFoundError:
        print("Input file not found:", INPUT_FILE)
        return

    # PARSE AND VALIDATE
    for line_number, line in enumerate(lines, start=1):

        if not line.strip():
            rejects.append(
                (line_number, line.rstrip("\n"), "Blank line")
            )
            continue

        try:
            fields = parse_record(line)
        except csv.Error as error:
            rejects.append(
                (line_number, line.rstrip("\n"),
                 "CSV parsing error: " + str(error))
            )
            continue

        reason = validate_record(fields)

        if reason:
            rejects.append(
                (line_number, line.rstrip("\n"), reason)
            )
            continue

        # AGGREGATE
        work_order, date, employee, shift, hours = fields

        key = (employee.strip(), shift.strip().title())
        aggregates[key] += float(hours)

    # WRITE HUMAN REPORT
    with open(REPORT_FILE, "w") as file:

        file.write("SHIFT HOURS SUMMARY\n")
        file.write("=" * 65 + "\n")

        file.write(
            f"{'EMPLOYEE':<20}"
            f"{'SHIFT':<15}"
            f"{'TOTAL HOURS':>15}\n"
        )

        file.write("-" * 65 + "\n")

        for (employee, shift), total_hours in sorted(
            aggregates.items()
        ):
            file.write(
                f"{employee:<20}"
                f"{shift:<15}"
                f"{total_hours:>15.2f}\n"
            )

        file.write("-" * 65 + "\n")
        file.write(f"Valid records: {len(lines) - len(rejects)}\n")
        file.write(f"Rejected records: {len(rejects)}\n")

    # WRITE REJECTS CSV
    with open(REJECTS_FILE, "w", newline="") as file:

        writer = csv.writer(file)

        writer.writerow(["Line Number", "Rejected Line", "Reason"])

        writer.writerows(rejects)

    # DISPLAY RESULTS
    print("Processing completed.")
    print("Input records:", len(lines))
    print("Valid records:", len(lines) - len(rejects))
    print("Rejected records:", len(rejects))
    print("Report saved to:", REPORT_FILE)
    print("Rejects saved to:", REJECTS_FILE)


if __name__ == "__main__":
    main()

