import os
import re
import csv
from datetime import datetime
from collections import defaultdict

DATA_DIR = "data"
HISTORY_FILE = os.path.join(DATA_DIR, "run_history.csv")

# Part code: three letters, hyphen, three digits
PATTERN = re.compile(
    r"^\s*([A-Za-z]{3}-\d{3})\s*,\s*([^,]+?)\s*,\s*(\d+)\s*$"
)


# OLD PARSER - retained for comparison
#
# def parse_record(line):
#     fields = line.split(",")
#     if len(fields) != 3:
#         return None
#     return tuple(field.strip() for field in fields)


# NEW REGEX PARSER
def parse_record(line):
    match = PATTERN.fullmatch(line)

    if not match:
        return None

    part_code, description, quantity = match.groups()

    return part_code, description.strip(), int(quantity)


def validate_record(record):
    if record is None:
        return "Invalid record format or part code"

    part_code, description, quantity = record

    if not description:
        return "Missing description"

    if quantity <= 0:
        return "Quantity must be positive"

    return None


def write_report(filename, aggregates, processed, rejects):

    with open(filename, "w") as report:

        report.write("PLANT SHIFT / PART REPORT\n")
        report.write("=" * 65 + "\n")

        report.write(
            f"{'PART CODE':<15}"
            f"{'DESCRIPTION':<30}"
            f"{'QUANTITY':>12}\n"
        )

        report.write("-" * 65 + "\n")

        for code, description, quantity in sorted(aggregates):
            report.write(
                f"{code:<15}"
                f"{description:<30}"
                f"{quantity:>12}\n"
            )

        report.write("-" * 65 + "\n")
        report.write(f"Records processed: {processed}\n")
        report.write(f"Rejected records: {rejects}\n")


def append_history(filename, processed, rejects):

    # Job 11 datetime format
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    file_exists = os.path.exists(HISTORY_FILE)

    with open(HISTORY_FILE, "a", newline="") as history:

        writer = csv.writer(history)

        if not file_exists or os.path.getsize(HISTORY_FILE) == 0:
            writer.writerow([
                "Timestamp",
                "File Name",
                "Records Processed",
                "Rejects"
            ])

        writer.writerow([
            timestamp,
            filename,
            processed,
            rejects
        ])


def process_file(filepath):

    aggregates = defaultdict(int)
    rejects = []
    processed = 0

    filename = os.path.basename(filepath)

    print("\nProcessing:", filename)

    with open(filepath, "r", encoding="utf-8") as source:

        for line_number, line in enumerate(source, start=1):

            if not line.strip():
                rejects.append(
                    (line_number, line.rstrip("\n"), "Blank line")
                )
                continue

            processed += 1

            record = parse_record(line)
            reason = validate_record(record)

            if reason:
                rejects.append(
                    (line_number, line.rstrip("\n"), reason)
                )
                continue

            code, description, quantity = record

            aggregates[(code, description)] += quantity

    # Individual report
    report_name = os.path.splitext(filename)[0] + "_report.txt"
    report_path = os.path.join(DATA_DIR, report_name)

    write_report(
        report_path,
        [
            (code, description, quantity)
            for (code, description), quantity in aggregates.items()
        ],
        processed,
        len(rejects)
    )

    # Individual rejects file
    reject_path = os.path.join(
        DATA_DIR,
        os.path.splitext(filename)[0] + "_rejects.csv"
    )

    with open(reject_path, "w", newline="", encoding="utf-8") as reject_file:

        writer = csv.writer(reject_file)
        writer.writerow(["Line Number", "Rejected Line", "Reason"])
        writer.writerows(rejects)

    # Record execution history
    append_history(filename, processed, len(rejects))

    print("Records processed:", processed)
    print("Rejected:", len(rejects))
    print("Report:", report_path)

    return aggregates, processed, len(rejects)


def main():

    os.makedirs(DATA_DIR, exist_ok=True)

    # Avoid processing generated reports and reject files.
    input_files = sorted(
        filename
        for filename in os.listdir(DATA_DIR)
        if filename.lower().endswith(".txt")
        and not filename.lower().endswith("_report.txt")
    )

    if not input_files:
        print("No input .txt files found.")
        return

    plant_aggregates = defaultdict(int)
    total_processed = 0
    total_rejects = 0

    # PROCESS EVERY INPUT FILE
    for filename in input_files:

        filepath = os.path.join(DATA_DIR, filename)

        aggregates, processed, rejects = process_file(filepath)

        for key, quantity in aggregates.items():
            plant_aggregates[key] += quantity

        total_processed += processed
        total_rejects += rejects

    # WRITE COMBINED PLANT SUMMARY
    plant_report = os.path.join(DATA_DIR, "plant_summary.txt")

    write_report(
        plant_report,
        [
            (code, description, quantity)
            for (code, description), quantity
            in plant_aggregates.items()
        ],
        total_processed,
        total_rejects
    )

    print("\n" + "=" * 45)
    print("PLANT BATCH PROCESSING COMPLETE")
    print("=" * 45)
    print("Files processed:", len(input_files))
    print("Total records:", total_processed)
    print("Total rejects:", total_rejects)
    print("Plant summary:", plant_report)
    print("Run history:", HISTORY_FILE)


if __name__ == "__main__":
    main()

